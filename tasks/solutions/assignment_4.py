# 1. iter / next ხელით — ის, რასაც `for` შიგნით აკეთებს
# ─────────────────────────────────────────────────────────────
def manual_walk(data):
    """გაივლის მიმდევრობას `for`-ის გარეშე და აბრუნებს ელემენტების სიას.

        >>> manual_walk([10, 20, 30])
        [10, 20, 30]
    """
    iterator = iter(data)          # 1. იტერატორის აღება
    collected = []

    while True:
        try:
            item = next(iterator)  # 2. შემდეგი ელემენტი
        except StopIteration:      # 3. ელემენტები ამოიწურა
            break
        collected.append(item)

    return collected


# ─────────────────────────────────────────────────────────────
# 2. even_numbers(limit) — გენერატორი vs სია
# ─────────────────────────────────────────────────────────────
def even_numbers(limit):
    """აბრუნებს ლუწ რიცხვებს 0-დან limit-მდე (limit არ შედის).

        >>> list(even_numbers(10))
        [0, 2, 4, 6, 8]
    """
    for n in range(limit):
        if n % 2 == 0:
            yield n                # ფუნქცია „ჩერდება“ და მნიშვნელობას აბრუნებს


def even_numbers_list(limit):
    """იგივე ლოგიკა, მაგრამ სიად — შედარებისთვის."""
    return [n for n in range(limit) if n % 2 == 0]


def memory_comparison(limit=1_000_000):
    """აბრუნებს (გენერატორის_ბაიტები, სიის_ბაიტები)."""
    return sys.getsizeof(even_numbers(limit)), sys.getsizeof(even_numbers_list(limit))


# ─────────────────────────────────────────────────────────────
# 3. უსასრულო ფიბონაჩი
# ─────────────────────────────────────────────────────────────
def fibonacci():
    """უსასრულო გენერატორი: 0, 1, 1, 2, 3, 5, …

    `while True` აქ არ ჰკიდებს პროგრამას, რადგან `yield` ყოველ ბიჯზე
    აჩერებს ფუნქციას — იმდენ წევრს ვიღებთ, რამდენიც ვთხოვეთ.

        >>> list(itertools.islice(fibonacci(), 7))
        [0, 1, 1, 2, 3, 5, 8]
    """
    current, following = 0, 1

    while True:
        yield current
        current, following = following, current + following


# ─────────────────────────────────────────────────────────────
# 4. ფაილის მილსადენი — სამი გენერატორი ერთ ჯაჭვში
# ─────────────────────────────────────────────────────────────
def read_lines(path):
    """1. კითხულობს ფაილს ხაზ-ხაზ. მთლიან ფაილს მეხსიერებაში არ იღებს."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            yield line.rstrip("\n")


def only_errors(lines):
    """2. ტოვებს მხოლოდ იმ ხაზებს, სადაც ERROR წერია."""
    for line in lines:
        if "ERROR" in line:
            yield line


def to_message(lines):
    """3. თითოეული ხაზიდან იღებს მხოლოდ შეტყობინების ნაწილს."""
    for line in lines:
        yield line.split("] ", 1)[-1]


def error_messages(path):
    """სამივე რგოლი ერთ ჯაჭვად. არცერთი ხაზი ორჯერ არ იკითხება."""
    return to_message(only_errors(read_lines(path)))


def make_sample_log(path=LOG_FILE):
    """დემონსტრაციისთვის პატარა ლოგ-ფაილს ქმნის."""
    rows = [
        "[09:12 INFO] სერვისი გაეშვა",
        "[09:14 ERROR] ბაზასთან კავშირი გაწყდა",
        "[09:15 INFO] ხელახალი ცდა",
        "[09:16 ERROR] ავტორიზაცია ვერ მოხერხდა",
        "[09:20 WARN] პასუხი დაგვიანდა",
    ]
    path.write_text("\n".join(rows) + "\n", encoding="utf-8")
    return path



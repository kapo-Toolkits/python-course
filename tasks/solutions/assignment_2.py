# ─────────────────────────────────────────────────────────────
# 1. is_prime(n)
# ─────────────────────────────────────────────────────────────
def is_prime(n):
    """ამოწმებს, მარტივია თუ არა n.

    არგუმენტი:
        n (int): შესამოწმებელი მთელი რიცხვი

    აბრუნებს:
        bool: True, თუ n მარტივია; სხვა შემთხვევაში False

    მაგალითი:
        >>> is_prime(17)
        True
        >>> is_prime(1)
        False
    """
    if n < 2:                      # 0, 1 და უარყოფითები მარტივი არაა
        return False

    # საკმარისია გამყოფების შემოწმება √n-მდე: თუ n = a * b და a > √n,
    # მაშინ b < √n და ის უკვე შემოწმებული გვექნება.
    for divisor in range(2, int(n ** 0.5) + 1):
        if n % divisor == 0:
            return False

    return True


# ─────────────────────────────────────────────────────────────
# 2. convert_temp(value, to="F")
# ─────────────────────────────────────────────────────────────
def convert_temp(value, to="F"):
    """გარდაქმნის ცელსიუსს ფარენჰეიტში ან კელვინში.

    არგუმენტები:
        value (float): ტემპერატურა ცელსიუსით
        to (str): "F" — ფარენჰეიტი (ნაგულისხმევი), "K" — კელვინი

    აბრუნებს:
        float: გარდაქმნილი მნიშვნელობა; None — უცნობი ერთეულისას

    მაგალითი:
        >>> convert_temp(100)
        212.0
        >>> convert_temp(0, "K")
        273.15
    """
    unit = to.upper()

    if unit == "F":
        return value * 9 / 5 + 32
    if unit == "K":
        return value + 273.15

    return None                    # უცნობი ერთეული


# ─────────────────────────────────────────────────────────────
# 3. stats(*numbers)
# ─────────────────────────────────────────────────────────────
def stats(*numbers):
    """აბრუნებს მინიმუმს, მაქსიმუმს, ჯამსა და საშუალოს.

    არგუმენტები:
        *numbers: ნებისმიერი რაოდენობის რიცხვი

    აბრუნებს:
        tuple: (min, max, sum, mean); None — თუ არგუმენტი არ გადმოეცა

    მაგალითი:
        >>> stats(4, 8, 15, 16)
        (4, 16, 43, 10.75)
    """
    if not numbers:                # კიდურა შემთხვევა: stats()
        return None

    total = sum(numbers)
    return min(numbers), max(numbers), total, total / len(numbers)



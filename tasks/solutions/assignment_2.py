# 4. count_vowels(text)
# ─────────────────────────────────────────────────────────────
VOWELS = "aeiouAEIOU" + "აეიოუ"    # ლათინური + ქართული ხმოვნები


def count_vowels(text):
    """ითვლის ხმოვნებს ტექსტში (ლათინური და ქართული).

    არგუმენტი:
        text (str): ტექსტი

    აბრუნებს:
        int: ხმოვნების რაოდენობა

    მაგალითი:
        >>> count_vowels("Hello")
        2
        >>> count_vowels("პითონი")
        3
        >>> count_vowels("")
        0
    """
    count = 0

    for char in text:
        if char in VOWELS:
            count += 1

    return count



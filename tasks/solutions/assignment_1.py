# ─────────────────────────────────────────────────────────────
# 1. ლუწი/კენტი + ნიშანი
# ─────────────────────────────────────────────────────────────
number = int(input("1) შეიყვანე მთელი რიცხვი: "))

if number % 2 == 0:
    parity = "ლუწი"
else:
    parity = "კენტი"

if number > 0:
    sign = "დადებითი"
elif number < 0:
    sign = "უარყოფითი"
else:
    sign = "ნული"

print(f"   {number} — {parity}, {sign}")


# ─────────────────────────────────────────────────────────────
# 2. უდიდესი სამიდან — max()-ის გარეშე
# ─────────────────────────────────────────────────────────────
a = int(input("2) პირველი რიცხვი:  "))
b = int(input("   მეორე რიცხვი:    "))
c = int(input("   მესამე რიცხვი:   "))

# ჯერ ვვარაუდობთ, რომ პირველია უდიდესი, მერე ვამოწმებთ დანარჩენებს
largest = a

if b > largest:
    largest = b

if c > largest:
    largest = c

print(f"   უდიდესი: {largest}")


# ─────────────────────────────────────────────────────────────
# 3. შეფასების კონვერტორი (ECTS-ის ტიპური სკალა)
# ─────────────────────────────────────────────────────────────
score = int(input("3) ქულა (0–100): "))

if score < 0 or score > 100:
    print("   არაკორექტული ქულა — უნდა იყოს 0-სა და 100-ს შორის.")
elif score >= 91:
    print("   A — ფრიადი")
elif score >= 81:
    print("   B — ძალიან კარგი")
elif score >= 71:
    print("   C — კარგი")
elif score >= 61:
    print("   D — დამაკმაყოფილებელი")
elif score >= 51:
    print("   E — საკმარისი")
else:
    print("   F — ვერ ჩააბარა")


# ─────────────────────────────────────────────────────────────
# 4. ბილეთის ფასი
# ─────────────────────────────────────────────────────────────
FULL_PRICE = 20        # სრული ბილეთის ფასი

age = int(input("4) ასაკი: "))

if age < 0:
    price = None
    print("   ასაკი უარყოფითი ვერ იქნება.")
elif age < 6:
    price = 0
elif age <= 17:
    price = FULL_PRICE * 0.5
elif age <= 64:
    price = FULL_PRICE
else:
    price = FULL_PRICE * 0.7

if price is not None:
    if price == 0:
        print("   ბილეთი უფასოა")
    else:
        print(f"   ბილეთის ფასი: {price:.2f}")



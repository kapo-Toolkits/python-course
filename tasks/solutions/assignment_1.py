# 4) `6 <= age <= 17` ჯაჭვური შედარება მისასალმებელია (ლექცია 03).
#    ❌ `if age < 6 ... elif age < 18 ... elif age < 65 ... else` — სწორია;
#    `elif age > 17 and age < 65` — ასევე. მთავარია, საზღვრები არ დაიკარგოს:

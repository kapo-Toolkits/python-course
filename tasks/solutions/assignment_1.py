#    ❌ ნამდვილი შეცდომაა პირობების აღმავალი რიგი (`if score >= 51` პირველი) —
#    მაშინ 95 ქულაც „E“-ს მიიღებს. ეს ყველაზე მნიშვნელოვანი შესამოწმებელია.
